//! Game-overlay settings; external window skins/fonts remain in the modifier.
use crate::paint::Argb;
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum InfoMode {
    #[default]
    Off,
    Basic,
    Advanced,
}
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum IndexMode {
    #[default]
    Off,
    Front,
    All,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Options {
    pub info: InfoMode,
    pub index: IndexMode,
    pub colors: Colors,
    pub marker_duration: u32,
    pub wavelength_records: u8,
    pub show_me: bool,
    pub plant_offset: bool,
    pub produce_cd: bool,
    pub cob_cd: bool,
    pub cob_gloom_hp: bool,
    pub lily_pot_hp: bool,
    pub pumpkin_hp: bool,
    pub nut_spike_hp: bool,
    pub other_plant_hp: bool,
    pub crater: bool,
    pub ice_trail: bool,
    pub hp_style: bool,
    pub giga_stat: bool,
    pub giga_hp: bool,
    pub giga_count: bool,
    pub garg_hp: bool,
    pub zomboni_count: bool,
    pub football_hp: bool,
    pub football_count: bool,
    pub jack_countdown: bool,
    pub jack_explosion_range: bool,
    pub total_hp: bool,
    pub show_speed: bool,
    pub cob_col_preview: bool,
    pub activation_time: bool,
    pub vase_stat: bool,
}
impl Default for Options {
    fn default() -> Self {
        Self {
            info: InfoMode::Off,
            index: IndexMode::Off,
            colors: Colors::default(),
            marker_duration: 300,
            wavelength_records: 3,
            show_me: true,
            plant_offset: true,
            produce_cd: true,
            cob_cd: true,
            cob_gloom_hp: true,
            lily_pot_hp: true,
            pumpkin_hp: true,
            nut_spike_hp: true,
            other_plant_hp: true,
            crater: true,
            ice_trail: true,
            hp_style: false,
            giga_stat: true,
            giga_hp: true,
            giga_count: true,
            garg_hp: true,
            zomboni_count: true,
            football_hp: true,
            football_count: true,
            jack_countdown: true,
            jack_explosion_range: true,
            total_hp: true,
            show_speed: true,
            cob_col_preview: true,
            activation_time: true,
            vase_stat: true,
        }
    }
}
